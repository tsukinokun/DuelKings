//---------------------------------------------------------------------------
//!	@file	Timer.cpp
//! @brief	デルタタイムを使用したタイマー
//! @author 山﨑愛
//---------------------------------------------------------------------------
#pragma once
#include <chrono>

class Timer
{
public:
    Timer() { Reset(); }

    //---------------------------------------------------------------------------
    // タイマーをリセットする
    //---------------------------------------------------------------------------
    void Reset();

    //---------------------------------------------------------------------------
    // 前回からの経過時間（秒）を取得し、内部時間を更新する
    //! @return delta_time（秒）
    //---------------------------------------------------------------------------
    float Tick();

    //---------------------------------------------------------------------------
    // 現在の経過時間（秒）を取得（内部時間は更新しない）
    //! @return delta_time（秒）
    //---------------------------------------------------------------------------
    float Peek() const;

private:
    std::chrono::steady_clock::time_point last_time_;
};
