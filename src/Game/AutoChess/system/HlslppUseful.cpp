//---------------------------------------------------------------------------------
//!	マウス座標を float2 で取得
//---------------------------------------------------------------------------------
float2 GetMouseFloat2()
{
    float2 pos;
    pos.x = (float)GetMouseX();
    pos.y = (float)GetMouseY();
    return pos;
}
