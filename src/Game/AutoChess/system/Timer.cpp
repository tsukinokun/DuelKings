//---------------------------------------------------------------------------
//!	@file	Timer.cpp
//! @brief	デルタタイムを使用したタイマー
//! @author 山﨑愛
//---------------------------------------------------------------------------
#include "Timer.h"
//---------------------------------------------------------------------------
//! @brief タイマーをリセットする
//---------------------------------------------------------------------------
void Timer::Reset()
{
    last_time_ = std::chrono::steady_clock::now();
}

//---------------------------------------------------------------------------
//! @brief 前回からの経過時間（秒）を取得し、内部時間を更新する
//---------------------------------------------------------------------------
float Timer::Tick()
{
    auto                         now   = std::chrono::steady_clock::now();
    std::chrono::duration<float> delta = now - last_time_;
    last_time_                         = now;
    return delta.count();
}

//---------------------------------------------------------------------------
//! @brief 現在の経過時間（秒）を取得（内部時間は更新しない）
//---------------------------------------------------------------------------
float Timer::Peek() const
{
    auto                         now   = std::chrono::steady_clock::now();
    std::chrono::duration<float> delta = now - last_time_;
    return delta.count();
}
