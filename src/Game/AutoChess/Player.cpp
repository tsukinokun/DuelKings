#include "Agent.h"
#include "Player.h"
#include "Piece.h"
#include "PieceStand.h"
//---------------------------------------------------------------------------------
//!	初期化
//---------------------------------------------------------------------------------
bool Player::Init()
{
    __super::Init();
    stand_ = Scene::Object::Create<PieceStand>();    // ピーススタンドを作成
    SetName("Player");
    return true;
}

//---------------------------------------------------------------------------------
//!	更新
//---------------------------------------------------------------------------------
void Player::Update()
{
    if(IsKeyDown(KEY_INPUT_SPACE)) {
        if(auto stand = stand_.lock()) {
            stand->PieceInit();    // ピースの初期化
        }
    }
    __super::Update();
}

//---------------------------------------------------------------------------------
//!	描画
//---------------------------------------------------------------------------------
void Player::Draw()
{
    __super::Draw();
}

//---------------------------------------------------------------------------------
//!	終了
//---------------------------------------------------------------------------------
void Player::Exit()
{
    __super::Exit();
}

//---------------------------------------------------------------------------------
//!	GUI表示
//---------------------------------------------------------------------------------
void Player::GUI()
{
    __super::GUI();
}
