#pragma once
//------------------------------------------------------
//! @brief 駒のレベル別ステータス定義
//------------------------------------------------------
struct LevelData
{
    int attack_     = 0;    //!< 攻撃力
    int hp_         = 0;    //!< 体力
    int move_range_ = 0;    //!< 移動距離

    //--------------------------------------------------
    //! @brief シリアライズ関数
    //! @param ar アーカイブ
    //! @note Cereal用のシリアライズ関数
    //--------------------------------------------------
    template <class Archive>
    void serialize(Archive& ar)
    {
        ar(CEREAL_NVP(attack_), CEREAL_NVP(hp_), CEREAL_NVP(move_range_));
    }
};
