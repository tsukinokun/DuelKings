#include "Piece.h"
#include <Game/AutoChess/system/GameConst.h>
//---------------------------------------------------------------------------------
//!	初期化
//---------------------------------------------------------------------------------
bool Piece::Init()
{
    __super::Init();
    SetTranslate(float3(0.0f, 0.5f, 0.0f));    // 初期位置を設定
    SetName("Piece");
    return true;
}

//---------------------------------------------------------------------------------
//!	更新
//---------------------------------------------------------------------------------
void Piece::Update()
{
    __super::Update();
}

//---------------------------------------------------------------------------------
//!	描画
//---------------------------------------------------------------------------------
void Piece::Draw()
{
    __super::Draw();
    float3 pos = GetTranslate();
    DrawSphere3D(cast(pos), RADIUS_, 16, GetColor(255, 0, 255), GetColor(255, 0, 255), TRUE);
    //選択中なら
    if(is_selected_) {
        //位置を取得
        pos       = GetTranslate();
        pos.y     = 0.0f;    //y座標を0にする
        float3 p1 = float3(-SQUARE_HALF, -0.1f, -SQUARE_HALF) + pos;
        float3 p2 = float3(SQUARE_HALF, 0.1f, SQUARE_HALF) + pos;
        SetDrawBlendMode(DX_BLENDMODE_ALPHA, 200);
        DrawCube3D(cast(p1), cast(p2), GetColor(255, 0, 255), GetColor(255, 0, 255), TRUE);
        SetDrawBlendMode(DX_BLENDMODE_ALPHA, 255);
    }
}

//---------------------------------------------------------------------------------
//!	終了
//---------------------------------------------------------------------------------
void Piece::Exit()
{
    __super::Exit();
}

//---------------------------------------------------------------------------------
//!	GUI表示
//---------------------------------------------------------------------------------
void Piece::GUI()
{
    __super::GUI();
}

//---------------------------------------------------------------------------------
//!	選択状態の設定
//---------------------------------------------------------------------------------
void Piece::SetSelect(bool is_selected)
{
    is_selected_ = is_selected;
}

//---------------------------------------------------------------------------------
//!	選択状態の取得
//---------------------------------------------------------------------------------
bool Piece::IsSelect()
{
    return is_selected_;
}
