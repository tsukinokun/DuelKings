#include "Piece.h"
//---------------------------------------------------------------------------------
//!	初期化
//---------------------------------------------------------------------------------
bool Piece::Init()
{
    __super::Init();
    SetName("Piece");
    return true;
}

//---------------------------------------------------------------------------------
//!	更新
//---------------------------------------------------------------------------------
void Piece::Update()
{
    __super::Update();
}

//---------------------------------------------------------------------------------
//!	描画
//---------------------------------------------------------------------------------
void Piece::Draw()
{
    __super::Draw();
    float3 pos = GetTranslate();
    DrawSphere3D(cast(pos), RADIUS_, 16, GetColor(255, 0, 255), GetColor(255, 0, 255), TRUE);
}

//---------------------------------------------------------------------------------
//!	終了
//---------------------------------------------------------------------------------
void Piece::Exit()
{
    __super::Exit();
}

//---------------------------------------------------------------------------------
//!	GUI表示
//---------------------------------------------------------------------------------
void Piece::GUI()
{
    __super::GUI();
}
