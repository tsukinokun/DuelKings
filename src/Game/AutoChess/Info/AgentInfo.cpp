#include "AgentInfo.h"
//---------------------------------------------------------------------------
// デフォルトコンストラクタ
//---------------------------------------------------------------------------
AgentInfo::AgentInfo()
{
    gold_ = 0;    // 所持金を初期化
}

//---------------------------------------------------------------------------
//!  所持金を取得する関数
//---------------------------------------------------------------------------
int AgentInfo::GetGold() const
{
    return gold_;
}

//---------------------------------------------------------------------------
//!  所持金を増やす関数
//---------------------------------------------------------------------------
void AgentInfo::AddGold(int gold)
{
    gold_ += gold;
}

//---------------------------------------------------------------------------
//!  所持金を減らす関数
//---------------------------------------------------------------------------
bool AgentInfo::SpendGold(int gold)
{
    if(gold_ < gold)
        return false;    // 残高不足
    gold_ -= gold;
    return true;
}
