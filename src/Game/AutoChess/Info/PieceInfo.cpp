#include "PieceInfo.h"
#include <Game/AutoChess/system/GameConst.h>
#include <System/Component/ComponentModel.h>
//---------------------------------------------------------------------------
//! デフォルトコンストラクタ
//---------------------------------------------------------------------------
PieceInfo::PieceInfo()
{
}
//---------------------------------------------------------------------------
//! @brief 駒の種類を取得
//---------------------------------------------------------------------------
std::string PieceInfo::GetTypeName() const
{
    return type_name_;
}

//---------------------------------------------------------------------------
//! @brief 駒の種類を設定
//---------------------------------------------------------------------------
void PieceInfo::SetTypeName(const std::string& type_name)
{
    type_name_ = type_name;
}

//---------------------------------------------------------------------------
//! @brief 所属エージェントを取得（有効なら）
//---------------------------------------------------------------------------
std::shared_ptr<Agent> PieceInfo::GetOwner() const
{
    return owner_agent_.lock();
}

//---------------------------------------------------------------------------
//! 駒のレベルを取得
//---------------------------------------------------------------------------
int PieceInfo::GetLevel() const
{
    return level_;
}

//---------------------------------------------------------------------------
//! 駒のレベルを設定
//---------------------------------------------------------------------------
void PieceInfo::SetLevel(int level)
{
    level_ = level;
}

//---------------------------------------------------------------------------
//! 駒のレベルを1上げる
//---------------------------------------------------------------------------
void PieceInfo::LevelUp()
{
    if(level_ < MAX_PIECE_LEVEL) {
        level_++;
    }
}

//---------------------------------------------------------------------------
//! @brief 所属エージェントを設定
//---------------------------------------------------------------------------
void PieceInfo::SetOwner(const std::weak_ptr<Agent>& agent)
{
    owner_agent_ = agent;
}
