#pragma once
#include <System/Scene.h>
#include "PieceInfo.h"
#include <Game/AutoChess/system/GameConst.h>
// 前方宣言
class AgentStatus
{
public:
    //@{

    //---------------------------------------------------------------------------
    // デフォルトコンストラクタ
    //---------------------------------------------------------------------------
    AgentStatus();

    //---------------------------------------------------------------------------
    //  所持金を取得する関数
    //! @retval 所持金
    //---------------------------------------------------------------------------
    int GetGold() const;

    //---------------------------------------------------------------------------
    //  所持金を増やす関数
    //! @param gold [in] 増やす金額
    //---------------------------------------------------------------------------
    void AddGold(int gold);

    //---------------------------------------------------------------------------
    //  所持金を減らす関数
    //! @param gold [in] 減らす金額
    //! @retval 残高が足りていれば true、足りなければ false
    //---------------------------------------------------------------------------
    bool SpendGold(int gold);

    //---------------------------------------------------------------------------
    //  体力を取得する関数
    //! @retval 体力
    //---------------------------------------------------------------------------
    int GetHP() const;

    //---------------------------------------------------------------------------
    //  体力を減らす関数
    //! @param amount [in] 減らす体力量
    //---------------------------------------------------------------------------
    void ApplyDamage(int amount);

    //@}

private:
    int gold_ = 0;               // エージェントの所持金
    int hp_   = MAX_AGENT_HP;    //エージェントの体力
};
