#pragma once
#include <System/Scene.h>
#include "PieceInfo.h"
#include <Game/AutoChess/system/GameConst.h>
// 前方宣言
class AgentStatus
{
public:
    //@{

    //---------------------------------------------------------------------------
    // デフォルトコンストラクタ
    //---------------------------------------------------------------------------
    AgentStatus();

    //---------------------------------------------------------------------------
    //  所持金を取得する関数
    //! @retval 所持金
    //---------------------------------------------------------------------------
    int GetGold() const;

    //---------------------------------------------------------------------------
    //  所持金を増やす関数
    //! @param gold [in] 増やす金額
    //---------------------------------------------------------------------------
    void AddGold(int gold);

    //---------------------------------------------------------------------------
    //  所持金を減らす関数
    //! @param gold [in] 減らす金額
    //! @retval 残高が足りていれば true、足りなければ false
    //---------------------------------------------------------------------------
    bool SpendGold(int gold);

    //---------------------------------------------------------------------------
    //  体力を取得する関数
    //! @retval 体力
    //---------------------------------------------------------------------------
    int GetHP() const;

    //---------------------------------------------------------------------------
    //  勝敗結果を更新する関数
    //! @param isWin [in] 今回の勝敗結果(true:勝ち)
    //---------------------------------------------------------------------------
    void UpdateResult(bool isWin);

    //---------------------------------------------------------------------------
    //  連勝数を取得する関数
    //! @retval 連勝数
    //---------------------------------------------------------------------------
    int GetWinStreak() const;

    //---------------------------------------------------------------------------
    //  連敗数を取得する関数
    //! @retval 連敗数
    //---------------------------------------------------------------------------
    int GetLoseStreak() const;

    //---------------------------------------------------------------------------
    // 前回が勝ちかどうかを取得する関数
    //! @retval true:勝ち、false:負け
    //---------------------------------------------------------------------------
    bool WasLastResultWin() const;

    //---------------------------------------------------------------------------
    //  体力を減らす関数
    //! @param amount [in] 減らす体力量
    //---------------------------------------------------------------------------
    void ApplyDamage(int amount);

    //@}

private:
    int  win_streak_  = 0;               // 連勝数
    int  lose_streak_ = 0;               // 連敗数
    bool last_result_ = false;           // 前回の勝敗結果(true:勝ち、false:負け)
    int  gold_        = 0;               // エージェントの所持金
    int  hp_          = MAX_AGENT_HP;    //エージェントの体力
};
