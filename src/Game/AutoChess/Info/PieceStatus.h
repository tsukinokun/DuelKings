//---------------------------------------------------------------------------
//!	@file	PieceStatus.h
//! @brief	ピースのステータスクラス、この情報バッファをピースの実体がインスタンスとして持つ
//! @author 山﨑愛
//---------------------------------------------------------------------------
#pragma once
#include <System/Scene.h>
class Agent;    // 前方宣言
class PieceStatus
{
public:
    //---------------------------------------------------------------------------
    // PieceStatus を構築するためのビルダークラス。
    // 各種ステータスを段階的に設定し、Build() によって PieceStatus を生成します。
    //---------------------------------------------------------------------------
    class Builder
    {
    public:
        // HP を設定する。
        Builder& HP(int hp)
        {
            hp_ = hp;
            return *this;
        }

        // 攻撃力を設定する。
        Builder& AttackPower(int power)
        {
            attack_power_ = power;
            return *this;
        }

        // 攻撃間隔を設定する。
        Builder& AttackInterval(float interval)
        {
            attack_interval_ = interval;
            return *this;
        }

        // 射程距離を設定する。
        Builder& AttackRange(float range)
        {
            attack_range_ = range;
            return *this;
        }

        // 移動速度を設定する。
        Builder& MoveSpeed(float speed)
        {
            move_speed_ = speed;
            return *this;
        }

        //レベルを設定する。
        Builder& Level(int level)
        {
            level_ = level;
            return *this;
        }

        // 設定された値をもとに PieceStatus を生成する。
        PieceStatus Build() const { return PieceStatus(level_, hp_, attack_power_, attack_interval_, attack_range_, move_speed_); }

    private:
        // 各ステータスの初期値（未設定時のデフォルト）。
        int   level_           = 1;
        int   hp_              = 100;
        int   attack_power_    = 0;
        float attack_interval_ = 1.0f;
        float attack_range_    = 0.0f;
        float move_speed_      = 0.0f;
    };

    //---------------------------------------------------------------------------
    // Builder のインスタンスを生成する。
    // PieceStatus::Create().HP(...).AttackPower(...).Build() のように使用する。
    //---------------------------------------------------------------------------
    static Builder Create() { return Builder(); }

    //-----------------------------------------------------------------------------
    // デフォルトコンストラクタ
    //-----------------------------------------------------------------------------
    PieceStatus();

    //---------------------------------------------------------------------------
    // HP を取得する。
    //! @retval 現在のHP
    //---------------------------------------------------------------------------
    int GetHP() const;

    //---------------------------------------------------------------------------
    // 最大HP を取得する。
    //! @retval 最大のHP
    //---------------------------------------------------------------------------
    int GetMaxHP() const;

    //---------------------------------------------------------------------------
    // 攻撃力を取得する。
    //! @retval 攻撃力
    //---------------------------------------------------------------------------
    int GetAttackPower() const;

    //---------------------------------------------------------------------------
    // 攻撃間隔を取得する
    //---------------------------------------------------------------------------
    float GetAttackInterval() const;

    //---------------------------------------------------------------------------
    // 射程距離を取得する。
    //! @retval 射程距離
    //---------------------------------------------------------------------------
    float GetAttackRange() const;

    //---------------------------------------------------------------------------
    // 移動速度を取得する。
    //! @retval 移動速度
    //---------------------------------------------------------------------------
    float GetMoveSpeed() const;

    //---------------------------------------------------------------------------
    // ピースのレベルを取得する。
    //! @retval ピースのレベル
    //---------------------------------------------------------------------------
    int GetLevel() const;

    //-----------------------------------------------------------------------------
    // ダメージを適用する。
    //! @param [in] amount ダメージ量
    //-----------------------------------------------------------------------------
    void ApplyDamage(int amount);

    //---------------------------------------------------------------------------
    // レベルを上げる関数
    //---------------------------------------------------------------------------
    void LevelUp();

    //---------------------------------------------------------------------------
    // レベルを設定する関数
    //! @param level [in] レベル
    //---------------------------------------------------------------------------
    void SetLevel(int level);

    //---------------------------------------------------------------------------
    // 死亡判定を行う関数
    //! @retval 死亡している場合 true 、そうでない場合 false
    //---------------------------------------------------------------------------
    bool IsDead() const;

private:
    //---------------------------------------------------------------------------
    // コンストラクタ（Builder からのみ呼ばれる）。
    //! @note 外部から直接インスタンス化されないように private にしている。
    //---------------------------------------------------------------------------
    PieceStatus(int level_, int hp, int power, float interval, float range, float speed);

private:
    // ステータス値の保持。
    int   level_ = 1;          //ピースのレベル、重ねた数、最大は3まで、これは必ず1から始まる
    int   hp_;                 // 現在のHP
    int   max_hp_;             // 最大HP
    int   attack_power_;       // 攻撃力
    float attack_interval_;    // 攻撃間隔(秒)
    float attack_range_;       // 射程距離
    float move_speed_;         // 移動速度
};
