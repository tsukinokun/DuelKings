//---------------------------------------------------------------------------
//!	@file	PieceInfo.h
//! @brief	ピースの情報クラス
//! @author 山﨑愛
//---------------------------------------------------------------------------
#pragma once
#include <System/Scene.h>
class Agent;    // 前方宣言
class PieceInfo
{
public:
    //@{
    //---------------------------------------------------------------------------
    // デフォルトコンストラクタ
    //---------------------------------------------------------------------------
    PieceInfo();

    //-------------------------------------------------------------------
    //! @class Builder
    //! @brief PieceInfo の初期化を担うビルダークラス
    //!
    //! @details 駒の種類・レベル・所属エージェントを順に設定し、
    //!          最終的に PieceInfo インスタンスを構築します。
    //-------------------------------------------------------------------
    class Builder
    {
    public:
        //-------------------------------------------------------------------
        //! @brief 駒の種類名を設定する
        //! @param type_name [in] 駒の種類名
        //! @return Builder 自身の参照（メソッドチェーン用）
        //-------------------------------------------------------------------
        Builder& TypeName(const std::string& type_name)
        {
            type_name_ = type_name;
            return *this;
        }

        //-------------------------------------------------------------------
        //! @brief 駒のレベルを設定する
        //! @param level [in] 駒のレベル（1以上）
        //! @return Builder 自身の参照（メソッドチェーン用）
        //-------------------------------------------------------------------
        Builder& Level(int level)
        {
            level_ = level;
            return *this;
        }

        //-------------------------------------------------------------------
        //! @brief 所属エージェントを設定する
        //! @param owner [in] 所属エージェントの weak_ptr
        //! @return Builder 自身の参照（メソッドチェーン用）
        //-------------------------------------------------------------------
        Builder& Owner(const std::weak_ptr<Agent>& owner)
        {
            owner_agent_ = owner;
            return *this;
        }

        //-------------------------------------------------------------------
        //! @brief PieceInfo インスタンスを構築する
        //! @return 初期化済みの PieceInfo インスタンス
        //-------------------------------------------------------------------
        PieceInfo Build() const { return PieceInfo(type_name_, level_, owner_agent_); }

    private:
        std::string          type_name_;
        int                  level_ = 1;
        std::weak_ptr<Agent> owner_agent_;
    };

    //-------------------------------------------------------------------
    //! @brief Builder のインスタンスを生成する
    //! @return PieceInfo::Builder のインスタンス
    //-------------------------------------------------------------------
    static Builder Create() { return Builder(); }

    //---------------------------------------------------------------------------
    // 駒の種類を取得
    //! @retval 駒の種類名
    //---------------------------------------------------------------------------
    std::string GetTypeName() const;

    //---------------------------------------------------------------------------
    // 駒の種類を設定
    //! @param 駒の種類名
    //---------------------------------------------------------------------------
    void SetTypeName(const std::string& type_name);

    //---------------------------------------------------------------------------
    // 所属エージェントを取得（有効なら）
    //! @retval 所属エージェントのポインタ
    //---------------------------------------------------------------------------
    std::shared_ptr<Agent> GetOwner() const;

    //---------------------------------------------------------------------------
    // 所属エージェントを設定
    //! @param agent [in] 所属エージェントのウィークポインタ
    //---------------------------------------------------------------------------
    void SetOwner(const std::weak_ptr<Agent>& agent);

    //@}
private:
    //-------------------------------------------------------------------
    //! @brief コンストラクタ（Builder からのみ呼ばれる）
    //! @param type_name 駒の種類名
    //! @param level 駒のレベル
    //! @param owner 所属エージェントの weak_ptr
    //-------------------------------------------------------------------
    PieceInfo(const std::string& type_name, int level, const std::weak_ptr<Agent>& owner);

private:
    std::string          type_name_ = "";    //ピースのタイプ名
    int                  level_     = 1;     //ピースのレベル
    std::weak_ptr<Agent> owner_agent_;       //オーナーのウィークポインタ
};
