//---------------------------------------------------------------------------
//!	@file	PieceStatusModifier.h
//! @brief	ピースのバフ・デバフを管理するクラス
//! @author 山﨑愛
//---------------------------------------------------------------------------
#pragma once
#include <System/Scene.h>
#include <Game/AutoChess/Info/IStatusModifierListener.h>
class Agent;    // 前方宣言
class PieceStatusModifier
{
public:
    //---------------------------------------------------------------------------
    // リスナーを設定する
    //! @param listener ステータス変更を受け取るリスナー（通常は Piece が実装）
    //---------------------------------------------------------------------------
    void SetListener(IStatusModifierListener* listener);

    //=============================
    // 最大HP
    //=============================

    //---------------------------------------------------------------------------
    // 最大HP加算値を増やす
    //! @param value 増加量
    //---------------------------------------------------------------------------
    void AddMaxHP(int value);

    //---------------------------------------------------------------------------
    // 最大HP加算値を減らす
    //! @param value 減少量
    //---------------------------------------------------------------------------
    void RemoveMaxHP(int value);

    //---------------------------------------------------------------------------
    // 最大HP加算値を取得する
    //! @return 最大HP加算値
    //---------------------------------------------------------------------------
    int GetAddMaxHP() const;

    //---------------------------------------------------------------------------
    // 最大HP倍率を増やす
    //! @param value 増加量(%)
    //---------------------------------------------------------------------------
    void AddRateMaxHP(float value);

    //---------------------------------------------------------------------------
    // 最大HP倍率を減らす
    //! @param value 減少量(%)
    //---------------------------------------------------------------------------
    void RemoveRateMaxHP(float value);

    //---------------------------------------------------------------------------
    // 最大HP倍率を取得する
    //! @return 最大HP倍率(%)
    //---------------------------------------------------------------------------
    float GetRateMaxHP() const;

    //=============================
    // 攻撃力
    //=============================
    //---------------------------------------------------------------------------
    // 攻撃力加算値を増やす
    //! @param value 増加量
    //---------------------------------------------------------------------------
    void AddAttackPower(int value);

    //---------------------------------------------------------------------------
    // 攻撃力加算値を減らす
    //! @param value 減少量
    //---------------------------------------------------------------------------
    void RemoveAttackPower(int value);

    //---------------------------------------------------------------------------
    // 攻撃力加算値を取得する
    //! @return 攻撃力加算値
    //---------------------------------------------------------------------------
    int GetAddAttackPower() const;

    //---------------------------------------------------------------------------
    // 攻撃力倍率を増やす
    //! @param value 増加量(%)
    //---------------------------------------------------------------------------
    void AddRateAttackPower(float value);

    //---------------------------------------------------------------------------
    // 攻撃力倍率を減らす
    //! @param value 減少量(%)
    //---------------------------------------------------------------------------
    void RemoveRateAttackPower(float value);

    //---------------------------------------------------------------------------
    // 攻撃力倍率を取得する
    //! @return 攻撃力倍率(%)
    //---------------------------------------------------------------------------
    float GetRateAttackPower() const;

    //=============================
    // 攻撃間隔
    //=============================
    //---------------------------------------------------------------------------
    //攻撃間隔加算値を増やす
    //! @param value 増加量(秒)
    //---------------------------------------------------------------------------
    void AddAttackInterval(float value);

    //---------------------------------------------------------------------------
    // 攻撃間隔加算値を減らす
    //! @param value 減少量(秒)
    //---------------------------------------------------------------------------
    void RemoveAttackInterval(float value);

    //---------------------------------------------------------------------------
    // 攻撃間隔加算値を取得する
    //! @return 攻撃間隔加算値(秒)
    //---------------------------------------------------------------------------
    float GetAddAttackInterval() const;

    //---------------------------------------------------------------------------
    // 攻撃間隔倍率を増やす
    //! @param value 増加量(秒%)
    //---------------------------------------------------------------------------
    void AddRateAttackInterval(float value);

    //---------------------------------------------------------------------------
    // 攻撃間隔倍率を減らす
    //! @param value 減少量(秒%)
    //---------------------------------------------------------------------------
    void RemoveRateAttackInterval(float value);

    //---------------------------------------------------------------------------
    // 攻撃間隔倍率を取得する
    //! @return 攻撃間隔倍率(秒%)
    //---------------------------------------------------------------------------
    float GetRateAttackInterval() const;

    //=============================
    // 物理防御力
    //=============================
    //---------------------------------------------------------------------------
    // 物理防御力加算値を増やす
    //! @param value 増加量
    //---------------------------------------------------------------------------
    void AddPhysicalDefense(int value);

    //---------------------------------------------------------------------------
    // 物理防御力加算値を減らす
    //! @param value 減少量
    //---------------------------------------------------------------------------
    void RemovePhysicalDefense(int value);

    //---------------------------------------------------------------------------
    // 物理防御力加算値を取得する
    //! @return 物理防御力加算値
    //---------------------------------------------------------------------------
    int GetAddPhysicalDefense() const;

    //---------------------------------------------------------------------------
    // 物理防御力倍率を増やす
    //! @param value 増加量(%)
    //---------------------------------------------------------------------------
    void AddRatePhysicalDefense(float value);

    //---------------------------------------------------------------------------
    // 物理防御力倍率を減らす
    //! @param value 減少量(%)
    //---------------------------------------------------------------------------
    void RemoveRatePhysicalDefense(float value);

    //---------------------------------------------------------------------------
    // 物理防御力倍率を取得する
    //! @return 物理防御力倍率(%)
    //---------------------------------------------------------------------------
    float GetRatePhysicalDefense() const;

    //=============================
    // 魔法防御力
    //=============================
    //---------------------------------------------------------------------------
    // 魔法防御力加算値を増やす
    //! @param value 増加量
    //---------------------------------------------------------------------------
    void AddMagicalDefense(float value);

    //---------------------------------------------------------------------------
    // 魔法防御力加算値を減らす
    //! @param value 減少量
    //---------------------------------------------------------------------------
    void RemoveMagicalDefense(float value);

    //---------------------------------------------------------------------------
    // 魔法防御力加算値を取得する
    //! @return 魔法防御力加算値
    //---------------------------------------------------------------------------
    float GetAddMagicalDefense() const;

    //---------------------------------------------------------------------------
    // 魔法防御力倍率を増やす
    //! @param value 増加量(%)
    //---------------------------------------------------------------------------
    void AddRateMagicalDefense(float value);

    //---------------------------------------------------------------------------
    // 魔法防御力倍率を減らす
    //! @param value 減少量(%)
    //---------------------------------------------------------------------------
    void RemoveRateMagicalDefense(float value);

    //---------------------------------------------------------------------------
    // 魔法防御力倍率を取得する
    //! @return 魔法防御力倍率(%)
    //---------------------------------------------------------------------------
    float GetRateMagicalDefense() const;

    //=============================
    // 全ステータス
    //=============================
    //---------------------------------------------------------------------------
    // 他のmodifierの内容を加算する
    //! @param other 加算するmodifier
    //---------------------------------------------------------------------------
    void AddModifier(const PieceStatusModifier& other);

    //---------------------------------------------------------------------------
    // 他のmodifierの内容を減算する
    //! @param other 減算するmodifier
    //---------------------------------------------------------------------------
    void RemoveModifier(const PieceStatusModifier& other);

private:
    //---------------------------------------------------------------------------
    //! @brief ステータス変更通知をリスナーへ送る
    //! @note listener_ が設定されている場合のみ呼び出される
    //---------------------------------------------------------------------------
    void NotifyChanged();

    IStatusModifierListener* listener_ = nullptr;    //ステータス変更を受け取るリスナー

    int   add_max_hp_            = 0;       // 最大HP
    float rate_max_hp_           = 0.0f;    // 最大HP(%)
    int   add_attack_power_      = 0;       // 攻撃力
    float rate_attack_power_     = 0.0f;    // 攻撃力(%)
    float add_attack_interval_   = 0.0f;    // 攻撃間隔(秒)
    float rate_attack_interval_  = 0.0f;    // 攻撃間隔(秒%)
    int   add_physical_defense_  = 0;       // 物理防御力
    float rate_physical_defense_ = 0.0f;    // 物理防御力(%)
    float add_magical_defense_   = 0.0f;    // 魔法防御力
    float rate_magical_defense_  = 0.0f;    // 魔法防御力(%)
};
