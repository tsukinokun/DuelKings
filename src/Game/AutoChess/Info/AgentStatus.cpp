#include "AgentStatus.h"
//---------------------------------------------------------------------------
// デフォルトコンストラクタ
//---------------------------------------------------------------------------
AgentStatus::AgentStatus()
{
    gold_ = 1000;    // 所持金を初期化
}

//---------------------------------------------------------------------------
//!  所持金を取得する関数
//---------------------------------------------------------------------------
int AgentStatus::GetGold() const
{
    return gold_;
}

//---------------------------------------------------------------------------
//!  所持金を増やす関数
//---------------------------------------------------------------------------
void AgentStatus::AddGold(int gold)
{
    gold_ += gold;
}

//---------------------------------------------------------------------------
//!  所持金を減らす関数
//---------------------------------------------------------------------------
bool AgentStatus::SpendGold(int gold)
{
    if(gold_ < gold)
        return false;    // 残高不足
    gold_ -= gold;
    return true;
}

//---------------------------------------------------------------------------
//!  体力を取得する関数
//---------------------------------------------------------------------------
int AgentStatus::GetHP() const
{
    return hp_;
}

//---------------------------------------------------------------------------
//!  勝敗結果を更新する関数
//---------------------------------------------------------------------------
void AgentStatus::UpdateResult(bool isWin)
{
    // 連勝・連敗数を更新
    if(isWin) {
        win_streak_++;
        lose_streak_ = 0;
    }
    else {
        lose_streak_++;
        win_streak_ = 0;
    }
    // 結果を更新
    last_result_ = isWin;
}

//---------------------------------------------------------------------------
//!  連勝数を取得する関数
//---------------------------------------------------------------------------
int AgentStatus::GetWinStreak() const
{
    return win_streak_;
}

//---------------------------------------------------------------------------
//!  連敗数を取得する関数
//---------------------------------------------------------------------------
int AgentStatus::GetLoseStreak() const
{
    return lose_streak_;
}

//---------------------------------------------------------------------------
//! 前回が勝ちかどうかを取得する関数
//---------------------------------------------------------------------------
bool AgentStatus::WasLastResultWin() const
{
    return last_result_;
}

//---------------------------------------------------------------------------
//!  体力を減らす関数
//---------------------------------------------------------------------------
void AgentStatus::ApplyDamage(int amount)
{
    hp_ -= amount;
}
