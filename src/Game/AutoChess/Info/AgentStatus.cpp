#include "AgentStatus.h"
//---------------------------------------------------------------------------
// デフォルトコンストラクタ
//---------------------------------------------------------------------------
AgentStatus::AgentStatus()
{
    gold_ = 1000;    // 所持金を初期化
}

//---------------------------------------------------------------------------
//!  所持金を取得する関数
//---------------------------------------------------------------------------
int AgentStatus::GetGold() const
{
    return gold_;
}

//---------------------------------------------------------------------------
//!  所持金を増やす関数
//---------------------------------------------------------------------------
void AgentStatus::AddGold(int gold)
{
    gold_ += gold;
}

//---------------------------------------------------------------------------
//!  所持金を減らす関数
//---------------------------------------------------------------------------
bool AgentStatus::SpendGold(int gold)
{
    if(gold_ < gold)
        return false;    // 残高不足
    gold_ -= gold;
    return true;
}

//---------------------------------------------------------------------------
//!  体力を取得する関数
//---------------------------------------------------------------------------
int AgentStatus::GetHP() const
{
    return hp_;
}

//---------------------------------------------------------------------------
//!  体力を減らす関数
//---------------------------------------------------------------------------
void AgentStatus::ApplyDamage(int amount)
{
    hp_ -= amount;
}
