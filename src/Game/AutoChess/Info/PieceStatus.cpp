//!	@file	PieceStatus.cpp
//! @brief	ピースのステータスクラス、この情報バッファをピースの実体がインスタンスとして持つ
//! @author 山﨑愛
//---------------------------------------------------------------------------
#include "PieceStatus.h"
#include <Game/AutoChess/system/GameConst.h>
#include <System/Component/ComponentModel.h>
//-----------------------------------------------------------------------------
// デフォルトコンストラクタ
//-----------------------------------------------------------------------------
PieceStatus::PieceStatus()
{
    level_        = 1;    //ピースのレベル、重ねた数、最大は3まで、これは必ず1から始まる
    hp_           = 0;
    max_hp_       = 0;
    attack_power_ = 0;
    attack_range_ = 0.0f;
    move_speed_   = 0.0f;
}
//---------------------------------------------------------------------------
// コンストラクタ（Builder からのみ呼ばれる）。
//---------------------------------------------------------------------------
PieceStatus::PieceStatus(int level, int hp, int power, float interval, float range, float speed, int physical_defense, float magical_defense)
    : level_(level)
    , hp_(hp)
    , max_hp_(hp)
    , attack_interval_(interval)
    , attack_power_(power)
    , attack_range_(range)
    , move_speed_(speed)
    , physical_defense_(physical_defense)
    , magical_defense_(magical_defense)
{
}
//---------------------------------------------------------------------------
//! HP を取得する。
//---------------------------------------------------------------------------
int PieceStatus::GetHP() const
{
    return hp_;
}

//---------------------------------------------------------------------------
//! 最大HP を取得する。
//---------------------------------------------------------------------------
int PieceStatus::GetMaxHP() const
{
    return max_hp_;
}

//---------------------------------------------------------------------------
//! 攻撃力を取得する。
//---------------------------------------------------------------------------
int PieceStatus::GetAttackPower() const
{
    return attack_power_;
}

//---------------------------------------------------------------------------
//! 攻撃間隔を取得する。
//---------------------------------------------------------------------------
float PieceStatus::GetAttackInterval() const
{
    return attack_interval_;
}

//---------------------------------------------------------------------------
//! 射程距離を取得する。
//---------------------------------------------------------------------------
float PieceStatus::GetAttackRange() const
{
    return attack_range_;
}

//---------------------------------------------------------------------------
//! 移動速度を取得する。
//---------------------------------------------------------------------------
float PieceStatus::GetMoveSpeed() const
{
    return move_speed_;
}

//---------------------------------------------------------------------------
//! ピースのレベルを取得する。
//---------------------------------------------------------------------------
int PieceStatus::GetLevel() const
{
    return level_;
}

//---------------------------------------------------------------------------
//! 物理防御を取得する。
//---------------------------------------------------------------------------
int PieceStatus::GetPhysicalDefense() const
{
    return physical_defense_;
}

//---------------------------------------------------------------------------
//! 魔法防御を取得する。
//---------------------------------------------------------------------------
float PieceStatus::GetMagicalDefense() const
{
    return magical_defense_;
}

//-----------------------------------------------------------------------------
//! ダメージを適用する。
//-----------------------------------------------------------------------------
void PieceStatus::ApplyDamage(int amount)
{
    hp_ = std::max(0, hp_ - amount);
}

//-----------------------------------------------------------------------------
//! HPを回復する。
//-----------------------------------------------------------------------------
void PieceStatus::Heal(int amount)
{
    // 最大HPを超えないように回復
    hp_ = std::min(max_hp_, hp_ + amount);
}

//---------------------------------------------------------------------------
//! レベルを上げる関数
//---------------------------------------------------------------------------
void PieceStatus::LevelUp()
{
    if(level_ < MAX_PIECE_LEVEL) {
        level_++;
    }
}
//---------------------------------------------------------------------------
//! レベルを設定する関数
//---------------------------------------------------------------------------
void PieceStatus::SetLevel(int level)
{
    level_ = level;
}

//---------------------------------------------------------------------------
//! 死亡判定を行う関数
//---------------------------------------------------------------------------
bool PieceStatus::IsDead() const
{
    return hp_ <= 0;
}
