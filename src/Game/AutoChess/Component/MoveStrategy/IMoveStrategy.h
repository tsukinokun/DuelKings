//---------------------------------------------------------------------------
//! @class IMoveStrategy
//! @brief ピースの移動ストラテジークラス
//---------------------------------------------------------------------------
class Piece;
class IMoveStrategy
{
public:
    //---------------------------------------------------------------------------
    //! @brief デストラクタ
    //---------------------------------------------------------------------------
    virtual ~IMoveStrategy() = default;

    //---------------------------------------------------------------------------
    //! @brief ピースの移動処理
    //! @param piece      [in] 移動するピース
    //! @param delta_time [in] デルタタイム
    //---------------------------------------------------------------------------
    virtual void Move(Piece* piece, float delta_time) = 0;
};
